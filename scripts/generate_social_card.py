pixels = bytearray(BG * (W * H))

def rect(x0,y0,x1,y1,color):
    x0=max(0,x0); y0=max(0,y0); x1=min(W,x1); y1=min(H,y1)
    for y in range(y0,y1):
        row=(y*W+x0)*3
        for _ in range(x0,x1):
            pixels[row:row+3]=bytes(color)
            row += 3

def draw_char(ch,x,y,scale,color):
    glyph=FONT.get(ch, FONT[" "])
    for gy,row in enumerate(glyph):
        for gx,v in enumerate(row):
            if v=="1":
                rect(x+gx*scale,y+gy*scale,x+(gx+1)*scale,y+(gy+1)*scale,color)

def draw_text(text,x,y,scale,color,spacing=1):
    cx=x
    for ch in text.upper():
        draw_char(ch,cx,y,scale,color)
        cx += (5+spacing)*scale
    return cx

def png_chunk(kind,data):
    return struct.pack(">I",len(data))+kind+data+struct.pack(">I",zlib.crc32(kind+data)&0xffffffff)

